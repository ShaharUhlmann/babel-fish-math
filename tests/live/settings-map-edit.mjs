// 3.0.0: the valid-edit path. (The first run's edit added a key "constructor", which
// the one-character rule rightly refuses; that was the test's mistake.)
const { connectTo } = await import('./cdp2.mjs');
const { setup, check, FILE } = await import('./lib.mjs');
const h = await setup();
const P = `app.plugins.plugins['babel-fish-math']`;
const E = `app.workspace.activeLeaf.view.editor`;
const AD = `app.vault.adapter`;
const DIR = `${P}.manifest.dir + '/maps/'`;
const K = async (k, w = 200) => { await h.key(k); await h.sleep(w); };
const readMap = (id) => h.ev(`${AD}.read(${DIR} + '${id}.json')`);
const typed = async (keys) => { await h.doc('', 0, 0); await h.key('i'); await h.keys(keys); await K('Escape'); return (await h.st()).text.trim(); };
await h.ev(`${P}.settings.hebrew || ${P}.toggle()`);
await h.ev(`app.setting.open(); app.setting.openTabById('babel-fish-math')`); await h.sleep(1500);
const sw = await connectTo(new RegExp('^Settings - ' + process.env.OBSIDIAN_TEST_VAULT));
await sw.send('Page.bringToFront'); await sw.sleep(300);
const clickBtn = (setting, label) => sw.ev(`(() => { const s = [...document.querySelectorAll('.setting-item')].find((x) => x.querySelector('.setting-item-name')?.textContent === ${JSON.stringify(setting)}); const b = [...s.querySelectorAll('button')].find((x) => x.textContent.startsWith(${JSON.stringify(label)})); b.click(); return 'ok'; })()`);
const modalBtn = (label) => sw.ev(`(() => { const ms = [...document.querySelectorAll('.modal:not(.mod-settings)')]; const m = ms[ms.length - 1]; [...m.querySelectorAll('button')].find((x) => x.textContent === ${JSON.stringify(label)}).click(); })()`);
const pick = (id) => sw.ev(`(() => { const s = [...document.querySelectorAll('.setting-item')].find((x) => x.querySelector('.setting-item-name')?.textContent === 'Key map'); const d = s.querySelector('select'); d.value = '${id}'; d.dispatchEvent(new Event('change')); })()`);
const count = () => sw.ev(`document.querySelectorAll('.modal:not(.mod-settings)').length`);
const toMain = async () => { await h.send('Page.bringToFront'); await h.ev(`${E}.focus()`); await h.sleep(200); };
const toSet = async () => { await sw.send('Page.bringToFront'); await sw.sleep(200); };

await clickBtn('Manage key maps', 'New'); await sw.sleep(500);
await sw.keys('edit test'); await modalBtn('Create'); await sw.sleep(600);
const id = await h.ev(`${P}.settings.activeMap`);
check('new map is active', id === 'edit-test', id);
await clickBtn('Manage key maps', 'Edit'); await sw.sleep(500);
const orig = JSON.parse(await readMap(id));
const next = JSON.stringify({ name: 'edit test', keys: { ...orig.keys, a: 'ס', '[': '[', ']': ']' } }, null, 2);
await sw.ev(`document.querySelector('.modal:not(.mod-settings) textarea').value = ${JSON.stringify(next)}`);
await modalBtn('Save'); await sw.sleep(600);
check('a valid edit saves and closes', (await count()) === 0 && JSON.parse(await readMap(id)).keys.a === 'ס', 'modals=' + await count());
await toMain();
let t = await typed('a');
check('the edited map types at once', t === 'ס', JSON.stringify(t));
t = await typed('[');
check('a map can turn bracket mirroring off', t.startsWith('['), JSON.stringify(t));
await h.doc('אס ש\n', 0, 0); await h.key('f'); await h.sleep(100); await h.key('a'); await h.sleep(250);
let s = await h.st(); await K('Escape');
check('f follows the active map', s.ch === 1, 'ch=' + s.ch);
await h.doc('אבג\n', 0, 0); await K('r', 100); await K('a', 250); s = await h.st();
check('r follows the active map', s.text.startsWith('סבג'), JSON.stringify(s.text));
await h.doc('אבג\n', 0, 0); await K('R'); await K('a'); await K('Escape'); s = await h.st();
check('Replace follows the active map', s.text.startsWith('סבג'), JSON.stringify(s.text));
await h.ev(`app.commands.executeCommandById('command-palette:open')`); await h.sleep(500); await h.keys('a');
const pv = await h.ev(`document.querySelector('input.prompt-input')?.value`); await K('Escape', 400);
check('the palette opens in the main window and follows the map', pv === 'ס', JSON.stringify(pv));
// The Hebrew OS fallbacks keep describing Windows' layout, not the map.
await h.doc('שלום עולם\n', 0, 0); await K('x'); await h.key('ץ', { code: 'Period', vk: 190 }); await h.sleep(250); s = await h.st();
check('Hebrew OS . still repeats, whatever the map', s.text.startsWith('ום'), JSON.stringify(s.text));
await toSet(); await pick('qwerty'); await sw.sleep(400); await toMain();
t = await typed('a'); check('switch to the default applies at once', t === 'ש', JSON.stringify(t));
await toSet(); await pick(id); await sw.sleep(400); await toMain();
t = await typed('a'); check('switch back applies at once', t === 'ס', JSON.stringify(t));
await h.ev(`(async () => { await app.plugins.disablePlugin('babel-fish-math'); await app.plugins.enablePlugin('babel-fish-math'); await new Promise((r) => setTimeout(r, 1500)); })()`);
t = await typed('a'); check('the active map survives a plugin reload', t === 'ס', JSON.stringify(t));
await h.ev(`(async () => { ${P}.settings.activeMap = 'qwerty'; await ${P}.saveSettings(); await ${AD}.remove(${DIR} + 'edit-test.json'); await app.plugins.disablePlugin('babel-fish-math'); await app.plugins.enablePlugin('babel-fish-math'); await new Promise((r) => setTimeout(r, 1500)); })()`);
await h.ev(`app.setting.close()`); sw.close(); await h.sleep(300);
console.log('errors:', h.logs.filter((l) => /error|exception|TypeError/i.test(l) && !/placeCursorAround|Invalid position/.test(l)).slice(-4).join(' | ') || '(none)');
console.log('final:', await h.ev(`(async () => { const f = app.vault.getAbstractFileByPath('${FILE}'); app.workspace.getLeavesOfType('markdown').forEach((l) => { if (l.view.file === f) l.detach(); }); if (f) await app.vault.delete(f); return ${P}.settings.activeMap + ' files=' + JSON.stringify((await ${AD}.list(${DIR})).files.map((x) => x.split('/').pop())); })()`));
h.close();
