// Builds main.js from src/ with no dependencies: node build.mjs
//
// Obsidian's community store installs only main.js, manifest.json and styles.css,
// so the sources are joined into one file. They share one top-level scope.
//
// The build fails, and writes nothing, if a core file:
//   • mentions a Vim internal (VIM_INTERNALS below, comments included), or
//   • uses anything declared at the top level of a Vim file, except VimIntegration.
// That is what keeps the split real despite the shared scope. It also fails if the
// joined file doesn't parse.
//
// src/default-map.json, the original key map, is inlined in place of its require line
// in core.js, for the same reason: the store wouldn't install a separate file.
//
// Options, for the tests:
//   --src <dir>   read the sources from <dir> (default: src next to this file)
//   --out <file>  write here (default: main.js next to this file)
//   --check       write nothing; fail if the output file differs from the build
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const HERE = dirname(fileURLToPath(import.meta.url));
const CORE_FILES = ['core.js'];
const VIM_FILES = ['vim.js'];
const ALLOWED_IN_CORE = new Set(['VimIntegration']);
const DEFAULT_MAP_FILE = 'default-map.json';
const DEFAULT_MAP_LINE = /^const DEFAULT_MAP = require\('\.\/default-map\.json'\);$/m;

const VIM_INTERNALS = [
  ['CodeMirrorAdapter', /CodeMirrorAdapter/],
  ['.cm6', /\.cm6\b/],
  // `.cm` is the Vim adapter on an EditorView; `editor.cm` is Obsidian's handle on
  // the EditorView itself. `.cm-…` is a CSS class.
  ['.cm (the Vim adapter)', /(?<!\beditor)\.cm(?![\w-])/],
  ['state.vim', /\bstate\.vim\b/],
  ['cm-vim', /cm-vim/],
  ['vim-motions', /vim-motions/],
  ['getKeymap', /getKeymap/],
  ['defineMotion', /defineMotion/],
  ['getMotion', /getMotion/],
  ['mapCommand', /mapCommand/i],
  ['multiSelectHandleKey', /multiSelectHandleKey/],
  ['handleKey', /\bhandleKey\b/],
  ['inputState', /\binputState\b/],
  ['keyBuffer', /\bkeyBuffer\b/],
  ['getTableDebugState', /getTableDebugState/],
];

function argValue(name) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : null;
}

// LF only, so the output doesn't depend on how the files were checked out.
const readSource = (dir, name) => readFileSync(join(dir, name), 'utf8').replace(/\r\n/g, '\n');

// Names declared at the top level of a source file (column 0, as written here).
function topLevelNames(text) {
  const names = new Set();
  for (const m of text.matchAll(/^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
  for (const m of text.matchAll(/^(?:const|let|var)\s+\{([^}]*)\}/gm)) {
    for (const part of m[1].split(',')) {
      const name = part.split(':').pop().trim();
      if (name) names.add(name);
    }
  }
  return names;
}

const withoutComments = (text) => text.replace(/(^|\s)\/\/.*$/gm, '$1');

function checkCore(name, text, vimNames) {
  const problems = [];
  const lines = text.split('\n');
  lines.forEach((line, i) => {
    for (const [label, re] of VIM_INTERNALS) {
      if (re.test(line)) problems.push(`${name}:${i + 1}: mentions the Vim internal ${label}`);
    }
  });
  withoutComments(text).split('\n').forEach((line, i) => {
    for (const m of line.matchAll(/[A-Za-z_$][\w$]*/g)) {
      if (vimNames.has(m[0]) && !ALLOWED_IN_CORE.has(m[0])) {
        problems.push(`${name}:${i + 1}: uses ${m[0]}, which is declared in a Vim file`);
      }
    }
  });
  return problems;
}

const srcDir = resolve(argValue('--src') || join(HERE, 'src'));
const outFile = resolve(argValue('--out') || join(HERE, 'main.js'));

const core = CORE_FILES.map((n) => [n, readSource(srcDir, n)]);
const vim = VIM_FILES.map((n) => [n, readSource(srcDir, n)]);

const vimNames = new Set();
for (const [, text] of vim) for (const n of topLevelNames(text)) vimNames.add(n);

const problems = core.flatMap(([n, text]) => checkCore(n, text, vimNames));
if (problems.length) {
  console.error('build failed: the core must not know about Vim internals.\n' + problems.join('\n'));
  process.exit(1);
}

// The default map goes in as a plain literal, normalised so line endings don't matter.
function inlineDefaultMap(text) {
  if (!DEFAULT_MAP_LINE.test(text)) {
    console.error('build failed: core.js has no require line for ' + DEFAULT_MAP_FILE + '.');
    process.exit(1);
  }
  let map;
  try {
    map = JSON.parse(readSource(srcDir, DEFAULT_MAP_FILE));
  } catch (err) {
    console.error('build failed: ' + DEFAULT_MAP_FILE + ': ' + err.message);
    process.exit(1);
  }
  return text.replace(DEFAULT_MAP_LINE, () => 'const DEFAULT_MAP = ' + JSON.stringify(map, null, 2) + ';');
}

const banner = '// GENERATED by build.mjs from src/ (' + [...CORE_FILES, DEFAULT_MAP_FILE, ...VIM_FILES].join(', ') +
  '). Do not edit: change src/, then run `node build.mjs`.\n';
const output = banner + [...core.map(([n, text]) => [n, inlineDefaultMap(text)]), ...vim]
  .map(([, text]) => text.replace(/\n*$/, '\n')).join('\n');

try {
  new vm.Script(output, { filename: 'main.js' });
} catch (err) {
  console.error('build failed: the joined file does not parse: ' + err.message);
  process.exit(1);
}

if (process.argv.includes('--check')) {
  if (!existsSync(outFile) || readFileSync(outFile, 'utf8') !== output) {
    console.error('check failed: ' + outFile + ' is not what the build produces. Run: node build.mjs');
    process.exit(1);
  }
  console.log('main.js is up to date');
} else {
  writeFileSync(outFile, output);
  console.log(`built ${outFile}: ${output.split('\n').length - 1} lines`);
}
